"""Generate lab_pygments.css for the docs theme lab (SMUDGY_THEME_LAB=1).

Run:  python docs/_lab/make_lab.py
Each light/dark Pygments pair is scoped to html[data-lab-code=<key>] and
to furo's light / dark / auto modes. Re-run after editing PAIRS.
"""

import os
import re

from pygments.formatters import HtmlFormatter

import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "_ext"))
from smudgy_pygments import SmudgyDark, SmudgyLight  # noqa: E402

PAIRS = {
    "smudgy": (SmudgyLight, SmudgyDark),
    "github": ("github-light", "github-dark"),
    "one": ("one-light", "one-dark"),
    "catppuccin": ("catppuccin-latte", "catppuccin-mocha"),
    "solarized": ("solarized-light", "solarized-dark"),
    "gruvbox": ("gruvbox-light", "gruvbox-dark"),
    "ayu": ("ayu-light", "ayu-mirage"),
    "tango-nord": ("tango", "nord-darker"),  # previous setup (baseline)
}


def scoped_defs(style, prefixes):
    """Token rules for `style`, scoped to `prefixes`; the bare .highlight
    rule is turned into --lab-code-bg / --lab-code-fg variables."""
    sel = ", ".join(f"{p} .highlight" for p in prefixes)
    out = []
    for line in HtmlFormatter(style=style).get_style_defs(sel).splitlines():
        if not line.startswith(prefixes[0]):
            continue  # unscoped pre/linenos rules
        m = re.match(r"(.*\.highlight) \{ background: ([^;]+);(?: color: ([^;}]+?);?)? \}", line)
        if m:
            fg = m.group(3) or "inherit"
            body_sel = ", ".join(prefixes)
            out.append(f"{body_sel} {{ --lab-style-bg: {m.group(2)}; --lab-style-fg: {fg}; }}")
        else:
            out.append(line)
    return out


def main():
    css = ["/* GENERATED by make_lab.py -- do not edit. */"]
    for key, (light, dark) in PAIRS.items():
        h = f'html[data-lab-code="{key}"]'
        css.append(f"/* {key} */")
        css += scoped_defs(light, [f'{h} body[data-theme="light"]'])
        css += scoped_defs(dark, [f'{h} body[data-theme="dark"]'])
        css.append("@media (prefers-color-scheme: light) {")
        css += scoped_defs(light, [f'{h} body[data-theme="auto"]'])
        css.append("}")
        css.append("@media (prefers-color-scheme: dark) {")
        css += scoped_defs(dark, [f'{h} body[data-theme="auto"]'])
        css.append("}")
    path = os.path.join(os.path.dirname(__file__), "lab_pygments.css")
    with open(path, "w") as f:
        f.write("\n".join(css) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
